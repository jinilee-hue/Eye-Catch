"""Card pictures + word list: FPR K Unit 1 Lesson 1 (Mm) — the 12 lesson words Croco Phonics level 1 uses
(textbook ledger b2_book_FPRK.json via Croco's tools/build_words.py: lemmas on the lesson pages that start with m and
have an official card + voice). Pictures = the official illustrations (Constella p-NOUN_<w>_illustration.png, the same
art as the FPR K cards), trimmed to their alpha box -> assets/cards/<w>.webp (max 420 px) + js/words.js.
uv run --with pillow python tools/build_cards.py
"""
import json, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
PH = pathlib.Path.home() / 'Documents/Jini/2026/Phonics'
IMG = PH / 'Phonics_island/fpr_assets/img'
CROCO = json.loads((PH / 'Croco-Phonics/js/words.js').read_text(encoding='utf-8').split('=', 1)[1].rstrip().rstrip(';'))
L1 = next(lv for lv in CROCO['levels'] if lv['lesson'] == 1)
OUT = ROOT / 'assets/cards'
VARIANT = {'map': '_2'}
OUT.mkdir(parents=True, exist_ok=True)
words = []
for w in L1['words']:
    # map: the single-map picture (the first one shows two maps) — the one Croco Phonics' card uses
    src = IMG / f"p-NOUN_{w['w']}_illustration{VARIANT.get(w['w'], '')}.png"
    im = Image.open(src).convert('RGBA')
    a = im.split()[3].point(lambda v: 255 if v > 8 else 0)
    im = im.crop(a.getbbox())
    im.thumbnail((420, 420), Image.LANCZOS)
    im.save(OUT / f"{w['w']}.webp", quality=88, method=6)
    words.append({'w': w['w'], 'ko': w['ko'], 'pages': w['pages'], 'img': f"assets/cards/{w['w']}.webp",
                  'ar': round(im.width / im.height, 3)})
    print(w['w'], im.size)
data = {'book': 'FPR K (From Phonics to Reading K)', 'unit': 1, 'lesson': 1, 'title': 'Mm', 'sound': 'm',
        'pages': L1['pages'], 'words': words}
# the same pictures as data URLs: the 3D cards draw them into a WebGL texture, and file:// pages can't put image
# FILES into WebGL (Toy Catch's lesson) — data URLs work everywhere
import base64
art = {w['w']: 'data:image/webp;base64,' + base64.b64encode((OUT / f"{w['w']}.webp").read_bytes()).decode() for w in words}
(ROOT / 'js/cards-art.js').write_text('/* generated by tools/build_cards.py — do not edit */\nwindow.EC_CARD_ART = '
                                      + json.dumps(art) + ';\n', encoding='utf-8')
(ROOT / 'js/words.js').write_text('/* generated by tools/build_cards.py — do not edit */\nwindow.EC_WORDS = '
                                  + json.dumps(data, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
