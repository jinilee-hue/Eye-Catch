"""Card pictures + word list: FPR K Unit 1 Lesson 1 (Mm) — all 18 m-words of the lesson pack (user 2026-11-22: the games use
the lesson pack, so 18 like Puzzle and Magic Block — mail mask mat match mice mouth joined the first 12; 'my' has no picture
to find). Source = the lesson pack (Phonics/공통자료/FP.K.U1L1-lesson-pack, read through
phonics-kit/tools/lessonpack.py): its pictures are the representative images (공통이미지자료/FPR K_U1,2 대표이미지).
Each picture is trimmed to its alpha box (moon keeps its square night sky) -> assets/cards/<w>.webp (max 420 px)
+ js/words.js (with `ph`, the expected phonemes the phonics-api judge compares with) + js/cards-art.js (data URLs).
uv run --with pillow python tools/build_cards.py
"""
import base64, json, pathlib, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
KIT = pathlib.Path.home() / 'Documents/Jini/2026/Phonics/phonics-kit'
sys.path.insert(0, str(KIT / 'tools'))
import lessonpack  # noqa: E402

TB = 'FP.K.U1L1'
WORDS = 'mail man map mask mat match meat mice milk mirror mitt monkey moon mop mouse mouth mug mushroom'.split()
assert len(WORDS) == 18
OUT = ROOT / 'assets/cards'
OUT.mkdir(parents=True, exist_ok=True)

pk = lessonpack.load(lessonpack.pack_dir(TB))
lessonpack.phonemes(pk)
words = []
for w in WORDS:
    e = pk['words'][w]
    im = Image.open(e['image']).convert('RGBA')
    a = im.split()[3].point(lambda v: 255 if v > 8 else 0)
    im = im.crop(a.getbbox())
    im.thumbnail((420, 420), Image.LANCZOS)
    im.save(OUT / f'{w}.webp', quality=88, method=6)
    words.append({'w': w, 'ko': e['ko'], 'ph': e['ph'], 'img': f'assets/cards/{w}.webp', 'ar': round(im.width / im.height, 3)})
    print(w, im.size, ' '.join(e['ph']))
data = {'book': pk['book'], 'pack': TB, 'resource_version': pk['resource_version'], 'unit': pk['unit'], 'lesson': 1,
        'title': 'Mm', 'sound': pk['sound']['text'], 'words': words}
# the same pictures as data URLs: the 3D cards draw them into a WebGL texture, and file:// pages can't put image
# FILES into WebGL (Toy Catch's lesson) — data URLs work everywhere
art = {w['w']: 'data:image/webp;base64,' + base64.b64encode((OUT / f"{w['w']}.webp").read_bytes()).decode() for w in words}
(ROOT / 'js/cards-art.js').write_text('/* generated by tools/build_cards.py — do not edit */\nwindow.EC_CARD_ART = '
                                      + json.dumps(art) + ';\n', encoding='utf-8')
(ROOT / 'js/words.js').write_text('/* generated by tools/build_cards.py — do not edit */\nwindow.EC_WORDS = '
                                  + json.dumps(data, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
